<#
.SYNOPSIS
  Wires the kit into the AI tools of this machine. Safe to run again after every pull.

.DESCRIPTION
  Claude Code : ~/.claude/{rules,hooks,agents,templates} and ~/.claude/skills/<skill> become
                directory junctions into the kit; ~/.claude/CLAUDE.md imports AGENTS.md and
                claude/CLAUDE.md.
  Copilot     : ~/.copilot/skills/<skill> junctions; ~/.copilot/copilot-instructions.md and the
                VS Code user prompt files (kit.instructions.md, kit-abap.instructions.md) are
                generated copies.
  Codex       : ~/.codex/AGENTS.md is a generated copy.
  An existing real folder is never replaced: the script stops and names it. An existing file that
  was not generated by this script is backed up first (*.bak).

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File scripts\install.ps1 -DryRun
#>
param([switch]$DryRun)

$ErrorActionPreference = 'Stop'
$Kit = Split-Path -Parent $PSScriptRoot
$Home_ = $env:USERPROFILE
$Marker = '<!-- generated by the kit (scripts/install.ps1); edit the kit, not this file -->'

function Say($text) { if ($DryRun) { Write-Output "[dry] $text" } else { Write-Output $text } }

function Set-Junction($link, $target) {
    if (Test-Path -LiteralPath $link) {
        $item = Get-Item -LiteralPath $link -Force
        if ($item.LinkType -eq 'Junction') {
            if (($item.Target | Select-Object -First 1) -eq $target) { return }
            Say "relink $link"
            if (-not $DryRun) { [System.IO.Directory]::Delete($link) }   # removes the link only
        } else {
            throw "$link is a real folder, not a junction. Move its content into the kit first."
        }
    }
    Say "junction $link -> $target"
    if (-not $DryRun) {
        New-Item -ItemType Directory -Force -Path (Split-Path -Parent $link) | Out-Null
        New-Item -ItemType Junction -Path $link -Target $target | Out-Null
    }
}

function Set-GeneratedFile($path, $content) {
    if (Test-Path -LiteralPath $path) {
        $old = Get-Content -LiteralPath $path -Raw -Encoding UTF8
        if ($old -eq $content) { return }
        if ($old -notmatch [regex]::Escape($Marker) -and $old -notmatch 'generated by the kit') {
            Say "backup $path -> $path.bak"
            if (-not $DryRun) { Copy-Item -LiteralPath $path "$path.bak" -Force }
        }
    }
    Say "write $path"
    if (-not $DryRun) {
        New-Item -ItemType Directory -Force -Path (Split-Path -Parent $path) | Out-Null
        [System.IO.File]::WriteAllText($path, $content, (New-Object System.Text.UTF8Encoding($false)))
    }
}

if ([Environment]::GetEnvironmentVariable('AI_KIT_HOME', 'User') -ne $Kit) {
    Say "set user environment variable AI_KIT_HOME=$Kit (new terminals and tools see it)"
    if (-not $DryRun) { [Environment]::SetEnvironmentVariable('AI_KIT_HOME', $Kit, 'User') }
}

$kitSlash = $Kit -replace '\\', '/'
$agents = Get-Content -LiteralPath "$Kit\AGENTS.md" -Raw -Encoding UTF8
$skills = Get-ChildItem -Directory "$Kit\skills" | Where-Object { Test-Path "$($_.FullName)\SKILL.md" }

# Copies outside the kit cannot resolve "the folder that holds this file": name the kit root.
$copyHeader = "$Marker`nKit root on this machine: ``$Kit`` (the relative paths below are relative to it).`n`n"

function Remove-StaleSkillLinks($folder) {
    # junctions into the kit whose skill was removed or renamed
    if (-not (Test-Path -LiteralPath $folder)) { return }
    Get-ChildItem -LiteralPath $folder -Force | Where-Object { $_.LinkType -eq 'Junction' } | ForEach-Object {
        $target = $_.Target | Select-Object -First 1
        if ($target -like "$Kit\skills\*" -and -not (Test-Path -LiteralPath $target)) {
            Say "remove stale link $($_.FullName)"
            if (-not $DryRun) { [System.IO.Directory]::Delete($_.FullName) }
        }
    }
}

# --- Claude Code -------------------------------------------------------------------------------
foreach ($dir in 'rules', 'hooks', 'agents', 'templates') { Set-Junction "$Home_\.claude\$dir" "$Kit\$dir" }
Remove-StaleSkillLinks "$Home_\.claude\skills"
foreach ($s in $skills) { Set-Junction "$Home_\.claude\skills\$($s.Name)" $s.FullName }
Set-GeneratedFile "$Home_\.claude\CLAUDE.md" (@"
<!-- generated by the kit (scripts/install.ps1); edit the kit, not this file -->
@$kitSlash/AGENTS.md
@$kitSlash/claude/CLAUDE.md
"@ + "`n")

# --- GitHub Copilot (CLI + VS Code) ------------------------------------------------------------
# ~/.copilot/skills for Copilot CLI; VS Code also lists ~/.claude/skills, so a skill may show twice there.
Remove-StaleSkillLinks "$Home_\.copilot\skills"
foreach ($s in $skills) { Set-Junction "$Home_\.copilot\skills\$($s.Name)" $s.FullName }
# ~/.copilot/copilot-instructions.md is read by Copilot CLI and by VS Code (all workspaces)
Set-GeneratedFile "$Home_\.copilot\copilot-instructions.md" ($copyHeader + $agents)
$prompts = "$env:APPDATA\Code\User\prompts"
$oldCopy = "$prompts\kit.instructions.md"   # earlier versions: same text as above, loaded twice
if ((Test-Path -LiteralPath $oldCopy) -and ((Get-Content -LiteralPath $oldCopy -Raw) -match 'generated by the kit')) {
    Say "remove $oldCopy (duplicate of copilot-instructions.md)"
    if (-not $DryRun) { Remove-Item -LiteralPath $oldCopy }
}
if (Test-Path "$env:APPDATA\Code\User") {
    $abap = Get-Content -LiteralPath "$Kit\.github\instructions\abap.instructions.md" -Raw -Encoding UTF8
    Set-GeneratedFile "$prompts\kit-abap.instructions.md" ($abap -replace '(?s)^(---.*?---\r?\n)', "`$1$copyHeader")
}

# --- Codex -------------------------------------------------------------------------------------
Set-GeneratedFile "$Home_\.codex\AGENTS.md" ($copyHeader + $agents)

Say "done. Kit: $Kit"
